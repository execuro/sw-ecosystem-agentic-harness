#!/usr/bin/env node
// Generates codex/agents/<name>.toml from agents/<name>.md.
//
// Codex plugins cannot ship sub-agents, so these TOMLs are adapters that
// `sw-setup` copies into the host's `.codex/agents/` on its Codex branch. They
// are committed and CI-diffed rather than built at install time, so the source
// in this repository stays byte-identical to what ships.
//
//   node scripts/gen-codex-agents.mjs           # write
//   node scripts/gen-codex-agents.mjs --check   # exit 1 on any diff
//
// What is carried over, and what is deliberately not:
//   name, description         -> carried from the agent frontmatter
//   body                      -> developer_instructions, verbatim
//   model                     -> only when the agent pins one; `inherit` is not a pin
//   tools:                    -> dropped. Codex agent TOML has no tool allow-list, and
//                                per-agent sandbox_mode / MCP keys are inherited from the
//                                parent rather than enforced. The only real
//                                bound is `[features] shell_tool` plus PreToolUse hooks
//                                keyed on agent_type, which sw-setup installs.
//   color, memory             -> dropped. Claude-Code-only, no Codex equivalent.

import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { splitFrontmatter, parseFrontmatter } from './frontmatter.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC_DIR = join(ROOT, 'agents');
const OUT_DIR = join(ROOT, 'codex', 'agents');

// Agents whose shell access is turned off in Codex. `sw-tender-editor` is a
// mechanical file worker with no Bash in its Claude tool list.
const NO_SHELL = new Set(['sw-tender-editor']);

/** TOML basic string, single line. */
function tomlString(value) {
  return JSON.stringify(String(value));
}

/** TOML multi-line literal string — verbatim, no escape processing. */
function tomlMultiline(value) {
  if (value.includes("'''")) {
    throw new Error("body contains ''' and cannot be a TOML literal string");
  }
  // A literal string may not end with a quote adjacent to the delimiter, and
  // the opening newline is stripped by the format, so it is added back.
  const body = value.replace(/\s+$/, '');
  if (body.endsWith("'")) throw new Error('body ends with a quote');
  return `'''\n${body}\n'''`;
}

function render(agent) {
  const lines = [
    '# Generated by scripts/gen-codex-agents.mjs — do not edit.',
    `# source: agents/${agent.file}`,
    `# source-sha256: ${agent.hash}`,
    '',
    `name = ${tomlString(agent.name)}`,
    `description = ${tomlString(agent.description)}`,
  ];
  if (agent.model) lines.push(`model = ${tomlString(agent.model)}`);
  lines.push('', `developer_instructions = ${tomlMultiline(agent.body)}`);
  if (NO_SHELL.has(agent.name)) lines.push('', '[features]', 'shell_tool = false');
  return lines.join('\n') + '\n';
}

function build() {
  const files = readdirSync(SRC_DIR).filter((f) => f.endsWith('.md')).sort();
  return files.map((file) => {
    const raw = readFileSync(join(SRC_DIR, file), 'utf8');
    const { frontmatter, body } = splitFrontmatter(raw, file);
    const fm = parseFrontmatter(frontmatter, file);
    if (!fm.name) throw new Error(`${file}: frontmatter has no name`);
    if (!fm.description) throw new Error(`${file}: frontmatter has no description`);
    if (fm.name !== file.replace(/\.md$/, '')) {
      throw new Error(`${file}: frontmatter name "${fm.name}" does not match the filename`);
    }
    const agent = {
      file,
      name: fm.name,
      description: fm.description,
      // `inherit` is the absence of a pin, not a pinnable Codex model id.
      model: fm.model && fm.model !== 'inherit' ? fm.model : null,
      body,
      hash: createHash('sha256').update(raw).digest('hex'),
    };
    return { path: join(OUT_DIR, `${fm.name}.toml`), content: render(agent) };
  });
}

const check = process.argv.includes('--check');
const generated = build();
let drift = [];

if (!check) mkdirSync(OUT_DIR, { recursive: true });

for (const { path, content } of generated) {
  const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (current === content) continue;
  if (check) drift.push(`${current === null ? 'missing' : 'stale'}: ${path}`);
  else writeFileSync(path, content);
}

// A renamed or deleted agent must not leave its TOML behind.
const expected = new Set(generated.map(({ path }) => path));
const present = existsSync(OUT_DIR)
  ? readdirSync(OUT_DIR).filter((f) => f.endsWith('.toml')).map((f) => join(OUT_DIR, f))
  : [];
for (const path of present) {
  if (expected.has(path)) continue;
  if (check) drift.push(`orphan: ${path}`);
  else throw new Error(`orphan TOML with no matching agent: ${path} — delete it`);
}

if (check && drift.length) {
  console.error('codex agent TOMLs are out of date:');
  for (const line of drift) console.error(`  ${line}`);
  console.error('\nRun: node scripts/gen-codex-agents.mjs');
  process.exit(1);
}

console.log(`${generated.length} codex agent TOML(s) ${check ? 'up to date' : 'written'}`);
