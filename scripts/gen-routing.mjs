#!/usr/bin/env node
// Renders everything derived from project/entry/router.md:
//
//   project/hooks/sw-knowledge-routing.mjs               the SubagentStart hook script
//   project/entry/cursor/sw-shopware-knowledge.mdc       Cursor's always-on rule
//
// The installer writes the router itself into each agent's entry file and
// copies these two files into the project. They are generated so the router
// text exists once and the copies cannot drift from it.
//
//   node scripts/gen-routing.mjs           # write
//   node scripts/gen-routing.mjs --check   # exit 1 on any diff

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ENTRY = join(ROOT, 'project', 'entry');
const HOOKS = join(ROOT, 'project', 'hooks');
const router = readFileSync(join(ENTRY, 'router.md'), 'utf8').trim();

const hook = `#!/usr/bin/env node
// GENERATED by scripts/gen-routing.mjs from project/entry/router.md — do not edit.
// Edit router.md, then run: npm run gen
// SubagentStart hook: injects the Shopware knowledge router into the sub-agent.
// Never blocks and never fails: any error still exits 0 with the router printed.

const ROUTER = [
${router.split('\n').map((l) => `  ${JSON.stringify(l)},`).join('\n')}
].join('\\n');

try {
  // Drain the hook payload; its content does not change the output.
  const { readFileSync } = await import('node:fs');
  readFileSync(0);
} catch {
  // No stdin, or unreadable. The router goes out regardless.
}

process.stdout.write(JSON.stringify({
  hookSpecificOutput: { hookEventName: 'SubagentStart', additionalContext: ROUTER },
}) + '\\n');
process.exit(0);
`;

const mdc = `---
description: Shopware project knowledge routing
alwaysApply: true
---

${router}
`;

const outputs = [
  [join(HOOKS, 'sw-knowledge-routing.mjs'), hook],
  [join(ENTRY, 'cursor', 'sw-shopware-knowledge.mdc'), mdc],
];

const check = process.argv.includes('--check');
const stale = [];
for (const [path, content] of outputs) {
  const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (check) {
    if (current !== content) stale.push(path.replace(`${ROOT}/`, ''));
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    console.log(`${path.replace(`${ROOT}/`, '')} written (${content.length} bytes)`);
  }
}
if (check) {
  if (stale.length) {
    console.error(`${stale.join(', ')} missing or out of date.\n\nRun: node scripts/gen-routing.mjs`);
    process.exit(1);
  }
  console.log('project/ generated files up to date');
}
