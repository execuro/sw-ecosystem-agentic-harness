#!/usr/bin/env node
// Generates copilot/agents/<name>.agent.md from agents/<name>.md.
//
// GitHub Copilot reads neither `.claude/agents/` nor a plugin's `agents/`:
// different directory, different frontmatter, different tool names. These
// adapters are what the installer CLI copies into a host's
// `.github/agents/`. They are committed and CI-diffed rather than built at
// install time, so the source stays byte-identical to what ships and a bad
// mapping becomes a red CI run on our own PR rather than a stranger's broken
// install.
//
//   node scripts/gen-copilot-agents.mjs           # write
//   node scripts/gen-copilot-agents.mjs --check   # exit 1 on any diff
//
// What is carried over, and what is deliberately not:
//   description               -> carried, and required by Copilot
//   name                      -> carried
//   body                      -> the agent prompt, verbatim
//   model                     -> only when the agent pins one; `inherit` is not a pin
//   tools:                    -> mapped through the alias table below. An `mcp__*`
//                                tool has no Copilot equivalent and is dropped, with
//                                the dropped names printed so the loss is visible in
//                                CI logs. An unknown non-`mcp__` name throws: a new
//                                Claude tool must not be silently lost.
//   color, memory             -> dropped. Claude-Code-only, no Copilot equivalent.

import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { splitFrontmatter, parseFrontmatter, toolList } from './frontmatter.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SRC_DIR = join(ROOT, 'agents');
const OUT_DIR = join(ROOT, 'copilot', 'agents');

// Copilot caps an agent prompt at 30,000 characters.
const MAX_PROMPT = 30000;

// Copilot's documented alias table for Claude tool names.
const TOOL_ALIASES = new Map(Object.entries({
  Bash: 'execute',
  Read: 'read',
  NotebookRead: 'read',
  Edit: 'edit',
  MultiEdit: 'edit',
  Write: 'edit',
  Grep: 'search',
  Glob: 'search',
  Task: 'agent',
  Agent: 'agent',
  WebSearch: 'web',
  WebFetch: 'web',
  TodoWrite: 'todo',
}));

/** Map a Claude tool list to Copilot names. Returns {tools, dropped}. */
function mapTools(names, file) {
  if (names === null) return { tools: null, dropped: [] };
  const tools = [];
  const dropped = [];
  for (const name of names) {
    if (name.startsWith('mcp__')) {
      dropped.push(name);
      continue;
    }
    const alias = TOOL_ALIASES.get(name);
    if (!alias) {
      throw new Error(
        `${file}: tool "${name}" has no Copilot alias. Add it to TOOL_ALIASES in ` +
          'scripts/gen-copilot-agents.mjs, or drop it from the agent.',
      );
    }
    if (!tools.includes(alias)) tools.push(alias);
  }
  return { tools, dropped };
}

/** YAML flow-scalar quoting for a single-line value. */
function yamlString(value) {
  return JSON.stringify(String(value));
}

function render(agent) {
  const lines = [
    '---',
    `name: ${yamlString(agent.name)}`,
    `description: ${yamlString(agent.description)}`,
  ];
  if (agent.model) lines.push(`model: ${yamlString(agent.model)}`);
  if (agent.tools) lines.push(`tools: [${agent.tools.join(', ')}]`);
  lines.push(
    '---',
    '',
    '<!-- Generated by scripts/gen-copilot-agents.mjs — do not edit. -->',
    `<!-- source: agents/${agent.file} -->`,
    `<!-- source-sha256: ${agent.hash} -->`,
    '',
  );
  return lines.join('\n') + agent.body.replace(/^\n+/, '');
}

function build() {
  const files = readdirSync(SRC_DIR).filter((f) => f.endsWith('.md')).sort();
  const allDropped = [];
  const out = files.map((file) => {
    const raw = readFileSync(join(SRC_DIR, file), 'utf8');
    const { frontmatter, body } = splitFrontmatter(raw, file);
    const fm = parseFrontmatter(frontmatter, file);
    if (!fm.name) throw new Error(`${file}: frontmatter has no name`);
    // Copilot rejects an agent file with no description.
    if (!fm.description) throw new Error(`${file}: frontmatter has no description`);
    if (fm.name !== file.replace(/\.md$/, '')) {
      throw new Error(`${file}: frontmatter name "${fm.name}" does not match the filename`);
    }
    const { tools, dropped } = mapTools(toolList(fm.tools), file);
    if (dropped.length) allDropped.push(`${file}: ${dropped.join(', ')}`);
    const agent = {
      file,
      name: fm.name,
      description: fm.description,
      // `inherit` is the absence of a pin, not a pinnable Copilot model id.
      model: fm.model && fm.model !== 'inherit' ? fm.model : null,
      tools,
      body,
      hash: createHash('sha256').update(raw).digest('hex'),
    };
    const content = render(agent);
    if (content.length > MAX_PROMPT) {
      throw new Error(
        `${file}: rendered agent is ${content.length} chars, over Copilot's ${MAX_PROMPT} cap`,
      );
    }
    return { path: join(OUT_DIR, `${fm.name}.agent.md`), content };
  });
  return { generated: out, allDropped };
}

const check = process.argv.includes('--check');
const { generated, allDropped } = build();
const drift = [];

if (!check) mkdirSync(OUT_DIR, { recursive: true });

for (const { path, content } of generated) {
  const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (current === content) continue;
  if (check) drift.push(`${current === null ? 'missing' : 'stale'}: ${path}`);
  else writeFileSync(path, content);
}

// A renamed or deleted agent must not leave its adapter behind.
const expected = new Set(generated.map(({ path }) => path));
const present = existsSync(OUT_DIR)
  ? readdirSync(OUT_DIR).filter((f) => f.endsWith('.agent.md')).map((f) => join(OUT_DIR, f))
  : [];
for (const path of present) {
  if (expected.has(path)) continue;
  if (check) drift.push(`orphan: ${path}`);
  else throw new Error(`orphan Copilot agent with no matching source: ${path} — delete it`);
}

// MCP tools have no Copilot equivalent. The drop is legitimate but must not be silent.
for (const line of allDropped) console.warn(`  dropped (no Copilot equivalent) ${line}`);

if (check && drift.length) {
  console.error('copilot agent adapters are out of date:');
  for (const line of drift) console.error(`  ${line}`);
  console.error('\nRun: node scripts/gen-copilot-agents.mjs');
  process.exit(1);
}

console.log(`${generated.length} copilot agent adapter(s) ${check ? 'up to date' : 'written'}`);
